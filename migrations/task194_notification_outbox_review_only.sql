-- Queue guarantees durable idempotent enqueue + atomic competing-worker lease.
-- It CANNOT guarantee exactly-once Telegram delivery (send+ACK are not atomic).
CREATE TABLE IF NOT EXISTS public.task194_notification_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dedupe_key text NOT NULL UNIQUE,
  job_name text NOT NULL,
  service_date date NOT NULL,
  chat_id text NOT NULL,
  body text NOT NULL CHECK (length(body) BETWEEN 1 AND 3500),
  state text NOT NULL DEFAULT 'PENDING'
    CHECK (state IN ('PENDING','SENDING','SENT','UNKNOWN')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  lease_token uuid,
  lease_until timestamptz,
  telegram_message_id bigint,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS task194_outbox_due_idx
  ON public.task194_notification_outbox (next_attempt_at, id)
  WHERE state IN ('PENDING','SENDING');
CREATE INDEX IF NOT EXISTS task194_outbox_unknown_idx
  ON public.task194_notification_outbox (created_at)
  WHERE state = 'UNKNOWN';
