CREATE OR REPLACE FUNCTION public.task194_claim_notifications(p_limit integer DEFAULT 5)
RETURNS SETOF public.task194_notification_outbox
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
  IF p_limit < 1 OR p_limit > 10 THEN
    RAISE EXCEPTION 'p_limit out of range' USING ERRCODE = '22023';
  END IF;
  -- A crashed sender has bounded 3 total attempts, then requires investigation.
  UPDATE public.task194_notification_outbox AS o
     SET state = 'UNKNOWN', last_error = 'delivery unacknowledged after max attempts',
         lease_token = NULL, lease_until = NULL, updated_at = now()
   WHERE o.state = 'SENDING' AND o.lease_until < now() AND o.attempts >= 3;
  RETURN QUERY
    WITH candidate AS (
      SELECT o.id
        FROM public.task194_notification_outbox AS o
       WHERE ((o.state = 'PENDING' AND o.next_attempt_at <= now())
           OR (o.state = 'SENDING' AND o.lease_until < now()))
         AND o.attempts < 3
       ORDER BY o.id
       FOR UPDATE SKIP LOCKED
       LIMIT p_limit
    )
    UPDATE public.task194_notification_outbox AS o
       SET state = 'SENDING', attempts = o.attempts + 1,
           lease_token = gen_random_uuid(), lease_until = now() + interval '90 seconds',
           updated_at = now()
      FROM candidate AS c WHERE o.id = c.id
    RETURNING o.*;
END; $$;

CREATE OR REPLACE FUNCTION public.task194_ack_notification(
  p_id bigint, p_lease uuid, p_message_id bigint
) RETURNS boolean LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE changed bigint;
BEGIN
  IF p_message_id IS NULL OR p_message_id <= 0 THEN
    RAISE EXCEPTION 'telegram message_id missing' USING ERRCODE = '22023';
  END IF;
  UPDATE public.task194_notification_outbox
     SET state='SENT', telegram_message_id=p_message_id,
         lease_token=NULL, lease_until=NULL, last_error=NULL, updated_at=now()
   WHERE id=p_id AND lease_token=p_lease AND state='SENDING';
  GET DIAGNOSTICS changed = ROW_COUNT;
  RETURN changed=1;
END; $$;

CREATE OR REPLACE FUNCTION public.task194_release_notification(
  p_id bigint, p_lease uuid, p_uncertain boolean, p_error text
) RETURNS boolean LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE changed bigint;
BEGIN
  UPDATE public.task194_notification_outbox
     SET state = CASE WHEN p_uncertain OR attempts >= 3 THEN 'UNKNOWN' ELSE 'PENDING' END,
         next_attempt_at = now() + interval '120 seconds',
         last_error = left(coalesce(p_error,'unknown send failure'), 300),
         lease_token=NULL, lease_until=NULL, updated_at=now()
   WHERE id=p_id AND lease_token=p_lease AND state='SENDING';
  GET DIAGNOSTICS changed = ROW_COUNT;
  RETURN changed=1;
END; $$;

