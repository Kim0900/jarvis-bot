def run(args, db=None, env=None, runner=RUNNER, cwd=None, timeout=120, dsn_override=None):
    e = dict(os.environ, PGDSN=dsn_override or dsn(db or "t_run"), **(env or {}))
    p = subprocess.run([sys.executable, str(runner)] + list(args), capture_output=True, text=True, env=e, timeout=timeout, cwd=cwd)
    try: rep = json.loads(p.stdout)
    except ValueError: rep = {}
    return p.returncode, rep, p.stderr

def variant(name, inject=None, text_replace=None):
    text = HARNESS
    if inject: text = text.replace("    execute v_gate;\n", "    execute v_gate;\n" + inject, 1)
    p = TMP / f"{name}.sql"; p.write_text(text, encoding="utf-8")
    ex = dict(EXPECT, sql_sha256=hashlib.sha256(text.encode()).hexdigest()); e = TMP / f"{name}.expect.json"; e.write_text(json.dumps(ex))
    return str(p), str(e), ex["sql_sha256"]

def t_run(db, extra=(), sha=None, sql=None, expect=None, env=None, timeout=120):
    args = ["--test-mode", "--sha256", sha or EXPECT["sql_sha256"]] + list(extra)
    if sql: args += ["--sql", sql]
    if expect: args += ["--expect", expect]
    return run(args, db=db, env=dict(TESTENV, **(env or {})), timeout=timeout)

