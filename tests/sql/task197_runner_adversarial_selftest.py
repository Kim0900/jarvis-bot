    ap_ = (root / "tests/sql/task197_approval.py"); ap_.write_text(ap_.read_text().replace("TRUST_ANCHOR_PUBKEY_SHA256 = None", f'TRUST_ANCHOR_PUBKEY_SHA256 = "{anchor}"'))
